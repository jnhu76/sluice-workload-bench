// Single inclusion point for the frozen fio headers (build/fio/upstream,
// tag fio-3.40, FIO_IOOPS_VERSION 37).
//
// Discipline (docs/fio-integration/FIO-ABI-QUALIFICATION.md §4.4/§5):
// fio's minmax.h defines function-like min()/max() macros, so any C++
// standard header included after fio.h fails to compile. This wrapper
// includes the engine's fixed standard-header set first and fio.h /
// optgroup.h last. Translation units that also use Sluice headers must
// include those BEFORE this wrapper; nothing may include standard headers
// after it. No extern "C" around fio headers (template with C linkage).
#pragma once

#ifndef _GNU_SOURCE
#define _GNU_SOURCE
#endif

#include <atomic>
#include <chrono>
#include <cstddef>
#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <exception>
#include <fcntl.h>
#include <memory>
#include <new>
#include <optional>
#include <stdexcept>
#include <string>
#include <string_view>
#include <sys/types.h>
#include <thread>
#include <type_traits>
#include <unordered_map>
#include <utility>
#include <variant>
#include <vector>

// fio's headers are plain C: included into C++ they would give these core
// functions C++ linkage and mangled undefined symbols the host fio process
// does not export. First-declaration linkage is sticky, so they are declared
// extern "C" up front and fio.h's own declarations then agree (ABIQ §5
// forbids wrapping the headers themselves).
struct thread_data;
struct fio_file;
struct io_u;
extern "C" {
ssize_t log_err(const char* format, ...);
int generic_open_file(struct thread_data* td, struct fio_file* f);
int generic_close_file(struct thread_data* td, struct fio_file* f);
int generic_get_file_size(struct thread_data* td, struct fio_file* f);
void io_u_mark_submit(struct thread_data* td, unsigned int nr);
}

#include "config-host.h" // generated by ./configure inside build/fio/upstream
#include "fio.h"
#include "optgroup.h"
