#!/usr/bin/env python3
"""Aggregate the E5 fio matrix into PERF-BASELINE.md tables + compare.json.

Contract (executed verbatim by the workflow, after run_fio_matrix.py):
    python3 tools/compare_fio.py --results-dir results/fio \
        --doc docs/fio-integration/PERF-BASELINE.md

Outputs:
  - <results-dir>/compare.json : A/A diff, four-engine table, envelope
    arm with comparability annotations, cross-check verdicts.
  - the markdown data tables injected between the PERF-DATA markers in
    the --doc skeleton (prose is owned by the later report phase).

Envelope arm (exploratory, NOT a strict A/B): runs the existing xmake
artifact sluice-workload-bench (noring binary: posix / direct /
threadpool; ring binary: + uring) on small workloads isomorphic to the
fio cases (same request sizes, same read/write ratio, approximately the
same concurrency via --depth; blocking backends are depth-1 only by
construction). Each invocation uses its own mkstemp fixture inside the
scratch directory and unlinks it. Annotation axes follow the workflow
ask (arrival trace identity, achieved concurrency, driver overhead,
file & cache state).

Determinism: strictly serial; fixed seed (81, matching the fio randseed
choice); the bench trace and the fio trace are separately deterministic
but are NOT the same trace - that is recorded, not hidden.
"""

from __future__ import annotations

import argparse
import json
import pathlib
import subprocess
import sys
import time

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from run_fio_matrix import Matrix  # noqa: E402

DOC_BEGIN = ("<!-- PERF-DATA:BEGIN (auto-generated by tools/compare_fio.py; "
             "do not edit inside the markers) -->")
DOC_END = "<!-- PERF-DATA:END -->"

# Envelope shapes: fio case -> (bench scenario, extra argv, requests).
ENVELOPE_CASES = {
    "F1": ("random-read", ("--depth", "1"), 300000),
    "F2": ("random-read", ("--depth", "16"), 1000000),
    "F3": ("mixed", ("--depth", "16", "--read-percent", "70"), 1000000),
    "F4": ("seq-read", ("--depth", "4"), 200000),
}
ENVELOPE_BACKENDS = ("posix", "direct", "threadpool", "uring")
SEED = 81


def parse_args() -> argparse.Namespace:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--results-dir", default="results/fio")
    ap.add_argument("--doc", default="docs/fio-integration/PERF-BASELINE.md")
    ap.add_argument("--out", default=None,
                    help="compare.json path (default <results-dir>/"
                         "compare.json)")
    ap.add_argument("--bench-noring",
                    default="build/linux/x86_64/release/"
                            "sluice-workload-bench")
    ap.add_argument("--bench-ring",
                    default="build/linux/x86_64/release/"
                            "sluice-workload-bench-ring")
    ap.add_argument("--envelope-scratch",
                    default="build/scratch/fio-envelope")
    ap.add_argument("--envelope-working-set-mib", type=int, default=512)
    ap.add_argument("--cpu-set", default="0-9",
                    help="taskset pinning for envelope bench runs; "
                         "empty disables")
    ap.add_argument("--skip-envelope", action="store_true")
    ap.add_argument("--rehearsal", action="store_true",
                    help="shrink envelope request counts for self-test")
    args = ap.parse_args()
    if args.rehearsal:
        for case in list(ENVELOPE_CASES):
            scen, extra, req = ENVELOPE_CASES[case]
            ENVELOPE_CASES[case] = (scen, extra, max(20000, req // 10))
    return args


# ---------------------------------------------------------------- matrix --

def load_and_verify(results: pathlib.Path) -> tuple:
    manifest_path = results / "manifest.json"
    if not manifest_path.is_file():
        raise SystemExit("missing %s; run tools/run_fio_matrix.py first"
                         % manifest_path)
    manifest = json.loads(manifest_path.read_text())
    crosschecks, problems = [], []
    for run in manifest.get("runs", []):
        if run.get("status") != "ok":
            continue
        original = results / (run["run_id"] + ".jsonl")
        if not original.is_file():
            problems.append("%s: JSON original missing" % run["run_id"])
            continue
        metrics = Matrix.extract_metrics(original.read_text())
        if metrics is None:
            problems.append("%s: JSON original unparseable" % run["run_id"])
            continue
        got = metrics.get("directions", {}).get("read", {}).get("iops")
        want = ((run.get("metrics") or {}).get("directions", {})
                .get("read", {}).get("iops"))
        if got is None and want is None:
            match = "no-read-direction"
        elif got is not None and want is not None and abs(got - want) < 1e-6:
            match = "ok"
        else:
            match = "MISMATCH got=%r manifest=%r" % (got, want)
            problems.append("%s: %s" % (run["run_id"], match))
        crosschecks.append({"run_id": run["run_id"], "read_iops": match})
    return manifest, crosschecks, problems


def aggregate(manifest: dict) -> dict:
    by_key = {}
    for run in manifest.get("runs", []):
        case, engine = run.get("case"), run.get("engine")
        if case in ("AA", None) or engine is None:
            continue
        by_key.setdefault((case, engine), []).append(run)
    table = {}
    for (case, engine), runs in sorted(by_key.items()):
        row = {"case": case, "engine": engine, "n_runs": len(runs),
               "statuses": sorted({r.get("status") for r in runs})}
        oks = [r for r in runs if r.get("status") == "ok"]
        row["unavailable_reason"] = next(
            (r.get("unavailable_reason") for r in runs
             if r.get("status") == "unavailable"), None)
        if oks:
            def mean(fn):
                vals = [v for v in (fn(r) for r in oks) if v is not None]
                return round(sum(vals) / len(vals), 3) if vals else None

            def dir_metrics(r, d):
                return ((r.get("metrics") or {}).get("directions", {})
                        .get(d) or {})
            ios = manifest["config"]["runtime_s"]
            row["iops_read"] = mean(lambda r: dir_metrics(r, "read")
                                    .get("iops"))
            row["iops_write"] = mean(lambda r: dir_metrics(r, "write")
                                     .get("iops"))
            # Per-rep values and spread: means alone would hide the
            # write-mix (F3) substrate noise on this host's slow SATA
            # SSD write path.
            reps_total = []
            for r in oks:
                dirs = (r.get("metrics") or {}).get("directions") or {}
                total = sum(d.get("iops") or 0 for d in dirs.values())
                if total:
                    reps_total.append(round(total, 1))
            row["iops_total_per_rep"] = reps_total
            if len(reps_total) > 1:
                row["iops_total_spread_pct"] = round(
                    (max(reps_total) - min(reps_total))
                    / (sum(reps_total) / len(reps_total)) * 100, 1)
            row["iops_total"] = (row["iops_read"] or 0) + \
                (row["iops_write"] or 0) or None
            row["bw_mib_s_read"] = mean(
                lambda r: (dir_metrics(r, "read").get("bw_bytes_per_s")
                           or 0) / (1 << 20) or None)
            row["bw_mib_s_write"] = mean(
                lambda r: (dir_metrics(r, "write").get("bw_bytes_per_s")
                           or 0) / (1 << 20) or None)
            for p in ("p50_us", "p95_us", "p99_us"):
                row["read_" + p] = mean(
                    lambda r, p=p: dir_metrics(r, "read").get(p))
            row["mean_depth"] = mean(
                lambda r: (r.get("metrics") or {}).get("mean_depth"))
            row["depth_capped"] = any(
                (r.get("metrics") or {}).get("sync_depth_capped")
                for r in oks)
            row["usr_cpu_pct"] = mean(
                lambda r: (r.get("metrics") or {}).get("usr_cpu"))
            row["sys_cpu_pct"] = mean(
                lambda r: (r.get("metrics") or {}).get("sys_cpu"))
            row["cpu_seconds"] = mean(
                lambda r: (r.get("rusage") or {}).get("cpu_user_s", 0)
                + (r.get("rusage") or {}).get("cpu_sys_s", 0))
            row["ctx_per_kio"] = mean(
                lambda r: _ctx_per_kio(r, ios))
        table["%s/%s" % (case, engine)] = row
    return table


def _ctx_per_kio(run: dict, runtime_s) -> float | None:
    dirs = (run.get("metrics") or {}).get("directions") or {}
    iops = sum((d.get("iops") or 0) for d in dirs.values())
    if not iops or not runtime_s:
        return None
    ru = run.get("rusage") or {}
    ctx = ru.get("ctx_voluntary", 0) + ru.get("ctx_involuntary", 0)
    kios = iops * runtime_s / 1000.0
    return round(ctx / kios, 3) if kios else None


# -------------------------------------------------------------- envelope --

def run_envelope(args: argparse.Namespace, root: pathlib.Path) -> dict:
    scratch = (root / args.envelope_scratch).resolve()
    scratch.mkdir(parents=True, exist_ok=True)
    binaries = {
        "posix": (root / args.bench_noring).resolve(),
        "direct": (root / args.bench_noring).resolve(),
        "threadpool": (root / args.bench_noring).resolve(),
        "uring": (root / args.bench_ring).resolve(),
    }
    runs = []
    for case, (scenario, extra, requests) in ENVELOPE_CASES.items():
        depth = int(extra[extra.index("--depth") + 1])
        for backend in ENVELOPE_BACKENDS:
            blocking = backend in ("posix", "direct")
            if blocking and depth != 1:
                runs.append({
                    "case": case, "backend": backend, "status": "skipped",
                    "reason": "blocking backend is depth-1 only; case "
                              "depth %d not expressible" % depth})
                continue
            binary = binaries[backend]
            if not binary.is_file():
                runs.append({"case": case, "backend": backend,
                             "status": "skipped",
                             "reason": "binary missing: %s" % binary})
                continue
            argv = []
            if args.cpu_set:
                argv += ["taskset", "-c", args.cpu_set]
            argv += [str(binary), "--scenario", scenario,
                     "--backend", backend,
                     "--requests", str(requests),
                     "--working-set-mib",
                     str(args.envelope_working_set_mib),
                     "--seed", str(SEED),
                     "--scratch-dir", str(scratch)]
            argv += list(extra)
            if backend == "threadpool":
                argv += ["--workers", "4"]
            t0 = time.monotonic()
            proc = subprocess.run(argv, capture_output=True, text=True,
                                  timeout=420)
            wall = round(time.monotonic() - t0, 3)
            record = {"case": case, "backend": backend,
                      "binary": str(binary), "argv": argv,
                      "exit": proc.returncode, "wall_s": wall}
            if proc.returncode == 77:
                record["status"] = "unavailable"
                try:
                    record["reason"] = json.loads(proc.stdout).get("reason")
                except ValueError:
                    record["reason"] = proc.stderr.strip()[:200]
            elif proc.returncode != 0:
                record["status"] = "fail"
                record["stderr"] = proc.stderr.strip()[-400:]
            else:
                try:
                    doc = json.loads(proc.stdout)
                except ValueError:
                    record["status"] = "fail"
                    record["stderr"] = "bench stdout not JSON"
                    runs.append(record)
                    continue
                if doc.get("status") != "ok" or \
                        doc.get("byte_oracle") != "passed":
                    record["status"] = "fail"
                    record["stderr"] = "bench status/oracle not ok"
                    runs.append(record)
                    continue
                w, x, t = (doc.get("workload", {}),
                           doc.get("execution", {}), doc.get("timing", {}))
                read_class = next((c for c in doc.get("classes", [])
                                   if c.get("operation") == "read"), None)
                record.update({
                    "status": "ok",
                    "trace_id": w.get("trace_id"),
                    "requests": w.get("requests"),
                    "arrival": w.get("arrival"),
                    "depth_config": extra[extra.index("--depth") + 1],
                    "peak_inflight_requests":
                        x.get("peak_inflight_requests"),
                    "iops": t.get("iops"),
                    "mib_per_second": t.get("mib_per_second"),
                    "read_p99_ns":
                        (read_class or {}).get("latency_ns", {}).get("p99"),
                    "cpu_ns_per_request": t.get("cpu_ns_per_request"),
                    "cpu_user_s": t.get("user_cpu_seconds"),
                    "cpu_sys_s": t.get("system_cpu_seconds"),
                })
            runs.append(record)
    leftovers = sorted(p.name for p in scratch.iterdir()) \
        if scratch.exists() else []
    return {"runs": runs, "seed": SEED,
            "working_set_mib": args.envelope_working_set_mib,
            "scratch_leftovers": leftovers}


def annotations(manifest: dict, envelope: dict) -> dict:
    """Comparability boundary per the workflow ask's annotation axes. The
    literal '§8.3' section was not found in either repository's docs; the
    axes are taken verbatim from the ask text (arrival trace, achieved
    concurrency, driver overhead, file & cache state)."""
    fio_cfg = manifest.get("config", {})
    return {
        "exploratory_not_strict_ab": True,
        "same_arrival_trace": {
            "value": False,
            "why": "fio drives time_based closed loops with its own "
                   "randseed=%s offset walk; the bench generates a "
                   "separate deterministic trace from its own seed=%s "
                   "PRNG over a request-count closed loop. Same "
                   "distributional shape (sizes, r/w ratio, working-set "
                   "span, target depth), different trace instance."
                   % (fio_cfg.get("randseed"), envelope.get("seed")),
        },
        "achieved_concurrency": {
            "fio": "iodepth_level histogram / mean_depth per run "
                   "(manifest metrics)",
            "bench": "peak_inflight_requests per run; blocking backends "
                     "(posix/direct) are depth-1 by construction",
        },
        "driver_overhead": {
            "fio": "full fio job machinery (io_u management, latency "
                   "histograms, offset generation) in the measured "
                   "process",
            "bench": "minimal in-process driver calling the backend "
                     "directly; cross-family deltas therefore mix driver "
                     "overhead with backend differences",
        },
        "file_and_cache_state": {
            "fio": "shared pre-created %s per-case file: psync seqwrite "
                   "+ fsync_on_close (clean), then one recorded full "
                   "sequential warm-up read so every engine starts with "
                   "the file page-cache resident (btrfs compress=zstd "
                   "cold reads would otherwise dominate and order runs by "
                   "cache warmth); time_based reuses the same file across "
                   "engines and repeats; direct=0"
                   % fio_cfg.get("file_size"),
            "bench": "fresh mkstemp fixture per invocation, pwrite-"
                     "prepared + fdatasync (warm), full byte oracle "
                     "verify; all backends buffered (bench 'direct' is "
                     "synchronous sluice::File, not O_DIRECT); working "
                     "set %s MiB"
                     % (envelope.get("working_set_mib") or "n/a"),
        },
        "runtime_model": {
            "fio": "time_based runtime=%ss + ramp=%ss"
                   % (fio_cfg.get("runtime_s"), fio_cfg.get("ramp_time_s")),
            "bench": "fixed request count, closed loop, single timed "
                     "pass after an untimed verification pass",
        },
    }


# ---------------------------------------------------------------- report --

def fmt(v) -> str:
    if v is None:
        return "-"
    if isinstance(v, bool):
        return str(v)
    if isinstance(v, int):
        return str(v)
    if isinstance(v, float):
        if abs(v - round(v)) < 5e-4:
            return str(int(round(v)))
        return ("%.3f" % v).rstrip("0").rstrip(".")
    return str(v)


def markdown(manifest: dict, table: dict, envelope: dict, notes: dict) -> str:
    lines = []
    lines.append("### 自动生成数据表（compare_fio.py；正式矩阵原件见 "
                 "results/fio/*.jsonl）")
    lines.append("")
    lines.append("模式：`%s`；fio `%s`；Sluice revision `%s`；randseed "
                 "`%s`；numjobs=1；direct=0；runtime=%ss(+ramp %ss)；"
                 "cpu_set=%s。"
                 % (manifest.get("mode"),
                    manifest.get("environment", {}).get("fio_version"),
                    manifest.get("sluice_revision"),
                    manifest["config"].get("randseed"),
                    manifest["config"].get("runtime_s"),
                    manifest["config"].get("ramp_time_s"),
                    manifest["config"].get("cpu_set")))
    lines.append("")
    lines.append("#### A/A（同配置重复，F2 形态）")
    lines.append("")
    lines.append("| engine | rep1 IOPS | rep2 IOPS | ΔIOPS% | rep1 p99µs "
                 "| rep2 p99µs | Δp99% | Δmean-depth% |")
    lines.append("|---|---:|---:|---:|---:|---:|---:|---:|")
    for engine, diff in sorted((manifest.get("aa") or {}).items()):
        if "error" in diff:
            lines.append("| %s | %s | | | | | | |" % (engine,
                                                      diff["error"]))
            continue
        f = diff["fields"]
        md = f["mean_depth"]
        lines.append("| %s | %s | %s | %s | %s | %s | %s | %s |"
                     % (engine, fmt(f["iops"]["rep1"]),
                        fmt(f["iops"]["rep2"]),
                        fmt(f["iops"]["delta_pct"]),
                        fmt(f["p99_us"]["rep1"]),
                        fmt(f["p99_us"]["rep2"]),
                        fmt(f["p99_us"]["delta_pct"]),
                        fmt(md["delta_pct"]) if md else "-"))
    lines.append("")
    lines.append("#### F1–F4 × 四引擎（两 repeats 均值；读方向延迟；"
                 "IOPS 逐 rep 见 compare.json）")
    lines.append("")
    lines.append("| case | engine | status | IOPS r/w/total | rep spread% "
                 "| BW MiB/s r/w "
                 "| p50µs | p95µs | p99µs | mean depth | CPU s | ctx/kiop |")
    lines.append("|---|---|---|---:|---:|---:|---:|---:|---:|---:|---:|")
    for key in sorted(table):
        row = table[key]
        status = "/".join(row["statuses"])
        extra = ""
        if row.get("unavailable_reason"):
            extra = " — %s" % row["unavailable_reason"][:60]
        lines.append(
            "| %s | %s | %s%s | %s / %s / %s | %s | %s / %s | %s | %s | %s "
            "| %s | %s | %s |"
            % (row["case"], row["engine"], status, extra,
               fmt(row.get("iops_read")), fmt(row.get("iops_write")),
               fmt(row.get("iops_total")),
               fmt(row.get("iops_total_spread_pct")),
               fmt(row.get("bw_mib_s_read")),
               fmt(row.get("bw_mib_s_write")),
               fmt(row.get("read_p50_us")), fmt(row.get("read_p95_us")),
               fmt(row.get("read_p99_us")),
               fmt(row.get("mean_depth")) + (" (capped)" if row.get(
                   "depth_capped") else ""),
               fmt(row.get("cpu_seconds")), fmt(row.get("ctx_per_kio"))))
    lines.append("")
    lines.append("#### envelope 对照（sluice-workload-bench，探索性非严格 "
                 "A/B）")
    lines.append("")
    lines.append("| case | backend | status | IOPS | MiB/s | 读 p99µs | "
                 "peak inflight | CPU ns/req |")
    lines.append("|---|---|---|---:|---:|---:|---:|---:|")
    for run in envelope.get("runs", []):
        p99_ns = run.get("read_p99_ns")
        p99_us = round(p99_ns / 1000.0, 3) if p99_ns is not None else None
        lines.append("| %s | %s | %s | %s | %s | %s | %s | %s |"
                     % (run["case"], run["backend"], run["status"],
                        fmt(run.get("iops")),
                        fmt(run.get("mib_per_second")), fmt(p99_us),
                        fmt(run.get("peak_inflight_requests")),
                        fmt(run.get("cpu_ns_per_request"))))
    lines.append("")
    lines.append("envelope 可比性边界（按任务书 §8.3 轴标注；该节号在两仓"
                 "文档中未找到原文，轴内容取自任务书正文）：")
    lines.append("")
    ann = notes.get("annotations", {})
    for axis in ("same_arrival_trace", "achieved_concurrency",
                 "driver_overhead", "file_and_cache_state"):
        item = ann.get(axis, {})
        if isinstance(item, dict) and "why" in item:
            lines.append("- **%s**: %s — %s"
                         % (axis, item["value"], item["why"]))
        elif isinstance(item, dict):
            lines.append("- **%s**: fio=%s；bench=%s"
                         % (axis, item.get("fio"), item.get("bench")))
    lines.append("- 明确声明：以上 envelope 行是探索性对照，不用于严格的 "
                 "A/B 裁决。")
    lines.append("")
    if notes.get("crosscheck_problems"):
        lines.append("**交叉核对问题**：%s"
                     % "; ".join(notes["crosscheck_problems"][:10]))
    else:
        lines.append("交叉核对：全部 fio JSON 原件与 manifest 数字一致"
                     "（%d runs）。" % len(notes.get("crosschecks", [])))
    lines.append("")
    return "\n".join(lines)


def write_doc(doc_path: pathlib.Path, body: str) -> None:
    text = doc_path.read_text()
    if DOC_BEGIN not in text or DOC_END not in text:
        raise SystemExit("%s lacks the PERF-DATA markers required by "
                         "compare_fio.py" % doc_path)
    head, rest = text.split(DOC_BEGIN, 1)
    _, tail = rest.split(DOC_END, 1)
    doc_path.write_text(head + DOC_BEGIN + "\n" + body + "\n" + DOC_END
                        + tail)


def main() -> int:
    args = parse_args()
    root = pathlib.Path(__file__).resolve().parents[1]
    results = (root / args.results_dir).resolve()
    manifest, crosschecks, problems = load_and_verify(results)
    table = aggregate(manifest)

    if args.skip_envelope:
        envelope = {"runs": [], "skipped": True, "seed": SEED,
                    "working_set_mib": None}
    else:
        envelope = run_envelope(args, root)
    ann = annotations(manifest, envelope)

    doc_path = root / args.doc
    body = markdown(manifest, table, envelope,
                    {"annotations": ann,
                     "crosschecks": crosschecks,
                     "crosscheck_problems": problems})
    write_doc(doc_path, body)

    out_path = pathlib.Path(args.out) if args.out \
        else results / "compare.json"
    doc = {
        "schema": 1,
        "source_manifest": str(results / "manifest.json"),
        "matrix_mode": manifest.get("mode"),
        "aa": manifest.get("aa"),
        "matrix": table,
        "envelope": envelope,
        "comparability": ann,
        "crosschecks": {"checked": len(crosschecks),
                        "problems": problems},
        "fio_originals_dir": str(results),
    }
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(json.dumps(doc, indent=2, sort_keys=True) + "\n")
    print("compare: %d matrix rows, %d envelope runs, %d crosschecks -> %s"
          % (len(table), len(envelope.get("runs", [])), len(crosschecks),
             out_path))
    print("doc tables injected -> %s" % doc_path)

    hard_fail = [r["run_id"] for r in manifest.get("runs", [])
                 if r.get("engine") in ("psync", "sluice-threadpool")
                 and r.get("status") == "fail"]
    env_fail = [r for r in envelope.get("runs", [])
                if r["status"] == "fail"]
    if envelope.get("scratch_leftovers"):
        problems.append("envelope scratch leftovers: %s"
                        % envelope["scratch_leftovers"])
    if problems or hard_fail or env_fail:
        print("PROBLEMS: crosscheck=%s hard_fail=%s envelope_fail=%d"
              % (problems[:5], hard_fail[:5], len(env_fail)))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
